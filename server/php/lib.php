<?php
/**
 * AIS BluePrinter - shared server library.
 *
 * Used by api.php (JSON API), install.php (web installer) and setup-cli.php (Docker / scripted
 * installs). Everything uses PDO with prepared statements; supported databases are MySQL /
 * MariaDB (pdo_mysql) and Microsoft SQL Server / Azure SQL (pdo_sqlsrv, or pdo_dblib as fallback).
 */

declare(strict_types=1);

namespace AISBP;

use PDO;
use RuntimeException;

const CONFIG_FILE = __DIR__ . '/config.php';
const LOCK_FILE = __DIR__ . '/install.lock';
/** Project ids follow the same rule as the browser (js/core/util.js ID_PATTERN). */
const ID_PATTERN = '/^[A-Za-z0-9][A-Za-z0-9_-]{0,63}$/';
/** Maximum accepted request body (bytes). Projects are small; this guards against abuse. */
const MAX_BODY = 5 * 1024 * 1024;
const DRIVERS = ['mysql' => 'MySQL / MariaDB', 'sqlsrv' => 'Microsoft SQL Server / Azure SQL'];

/**
 * Load config.php (created by the installer). Returns null when the application is not installed.
 * @return array<string,mixed>|null
 */
function load_config(): ?array
{
    if (!is_file(CONFIG_FILE)) {
        return null;
    }
    $config = require CONFIG_FILE;
    return is_array($config) ? $config : null;
}

/**
 * Open a PDO connection for the given database settings.
 * @param array<string,mixed> $db keys: driver, host, port, name, user, password
 */
function connect(array $db): PDO
{
    $driver = (string)($db['driver'] ?? '');
    $host = (string)($db['host'] ?? 'localhost');
    $port = (int)($db['port'] ?? 0);
    $name = (string)($db['name'] ?? '');
    if (!preg_match('/^[A-Za-z0-9_.-]{1,128}$/', $host) || !preg_match('/^[A-Za-z0-9_-]{1,128}$/', $name)) {
        throw new RuntimeException('Invalid database host or name.');
    }
    $options = [
        PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
        PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
    ];
    if ($driver === 'mysql') {
        $dsn = sprintf('mysql:host=%s;port=%d;dbname=%s;charset=utf8mb4', $host, $port ?: 3306, $name);
        $options[PDO::ATTR_EMULATE_PREPARES] = false;
    } elseif ($driver === 'sqlsrv') {
        if (in_array('sqlsrv', PDO::getAvailableDrivers(), true)) {
            $encrypt = !empty($db['encrypt']) ? 'yes' : 'no';
            $trust = !empty($db['trustServerCertificate']) ? 'yes' : 'no';
            $dsn = sprintf('sqlsrv:Server=%s,%d;Database=%s;Encrypt=%s;TrustServerCertificate=%s', $host, $port ?: 1433, $name, $encrypt, $trust);
        } elseif (in_array('dblib', PDO::getAvailableDrivers(), true)) {
            $dsn = sprintf('dblib:host=%s:%d;dbname=%s;charset=UTF-8', $host, $port ?: 1433, $name);
        } else {
            throw new RuntimeException('The PHP extension pdo_sqlsrv (or pdo_dblib) is not installed.');
        }
    } else {
        throw new RuntimeException('Unsupported database driver.');
    }
    return new PDO($dsn, (string)($db['user'] ?? ''), (string)($db['password'] ?? ''), $options);
}

/** Create the projects table when it does not exist yet (idempotent). */
function install_schema(PDO $pdo, string $driver): void
{
    $file = __DIR__ . '/schema/' . ($driver === 'sqlsrv' ? 'mssql.sql' : 'mysql.sql');
    $sql = (string)file_get_contents($file);
    // Statements are separated by lines containing only "-- ;;" so that T-SQL blocks stay intact.
    foreach (preg_split('/^\s*--\s*;;\s*$/m', $sql) ?: [] as $statement) {
        if (trim(preg_replace('/^\s*--.*$/m', '', $statement) ?? '') !== '') {
            $pdo->exec($statement);
        }
    }
}

/** Write config.php with restrictive permissions. */
function write_config(array $config): void
{
    $php = "<?php\n// Generated by the AIS BluePrinter installer. Keep this file private.\nreturn " . var_export($config, true) . ";\n";
    if (file_put_contents(CONFIG_FILE, $php, LOCK_EX) === false) {
        throw new RuntimeException('Could not write ' . basename(CONFIG_FILE) . '; check folder permissions.');
    }
    @chmod(CONFIG_FILE, 0640);
}

/** Generate a random API key. */
function random_key(): string
{
    return bin2hex(random_bytes(24));
}

/** Send a JSON response and stop. */
function json_response(array $data, int $status = 200): void
{
    http_response_code($status);
    header('Content-Type: application/json; charset=utf-8');
    header('Cache-Control: no-store');
    header('X-Content-Type-Options: nosniff');
    echo json_encode($data, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
    exit;
}

/** Repository for stored projects. */
final class ProjectRepository
{
    public function __construct(private PDO $pdo)
    {
    }

    /** @return list<array{id:string,name:string,modified:string}> */
    public function list(): array
    {
        $rows = $this->pdo->query('SELECT id, name, modified FROM aisbp_projects ORDER BY modified DESC')->fetchAll();
        return array_map(static fn(array $r) => [
            'id' => (string)$r['id'],
            'name' => (string)$r['name'],
            'modified' => (string)$r['modified'],
        ], $rows ?: []);
    }

    /**
     * Load the stored JSON document. Objects are decoded as stdClass so that empty objects
     * ({} - e.g. a project without connections) survive the round trip unchanged.
     */
    public function load(string $id): ?object
    {
        $stmt = $this->pdo->prepare('SELECT data FROM aisbp_projects WHERE id = ?');
        $stmt->execute([$id]);
        $data = $stmt->fetchColumn();
        if ($data === false) {
            return null;
        }
        $project = json_decode((string)$data, false, 64);
        return is_object($project) ? $project : null;
    }

    /**
     * Insert or update a project (portable upsert inside a transaction).
     * The document is stored as ASCII-only JSON (non-ASCII characters escaped as \uXXXX) so it
     * survives every driver / collation combination unchanged.
     * @param object $project decoded project (objects as stdClass, so {} stays {})
     */
    public function save(string $id, object $project): void
    {
        $meta = isset($project->meta) && is_object($project->meta) ? $project->meta : new \stdClass();
        $name = mb_substr(is_string($meta->name ?? null) ? $meta->name : 'Untitled', 0, 200);
        $modified = is_string($meta->modified ?? null) ? substr($meta->modified, 0, 40) : gmdate('c');
        $data = json_encode($project, JSON_UNESCAPED_SLASHES);
        if ($data === false) {
            throw new RuntimeException('Project could not be encoded.');
        }
        $this->pdo->beginTransaction();
        try {
            $stmt = $this->pdo->prepare('UPDATE aisbp_projects SET name = ?, modified = ?, data = ? WHERE id = ?');
            $stmt->execute([$name, $modified, $data, $id]);
            $exists = $this->pdo->prepare('SELECT COUNT(*) FROM aisbp_projects WHERE id = ?');
            $exists->execute([$id]);
            if ((int)$exists->fetchColumn() === 0) {
                $stmt = $this->pdo->prepare('INSERT INTO aisbp_projects (id, name, modified, data) VALUES (?, ?, ?, ?)');
                $stmt->execute([$id, $name, $modified, $data]);
            }
            $this->pdo->commit();
        } catch (\Throwable $e) {
            $this->pdo->rollBack();
            throw $e;
        }
    }

    public function delete(string $id): void
    {
        $stmt = $this->pdo->prepare('DELETE FROM aisbp_projects WHERE id = ?');
        $stmt->execute([$id]);
    }
}

/**
 * Repository for shared preferences (instance-wide; there are no user accounts).
 * The settings table is created on first use, so installations made before it existed keep working.
 */
final class SettingsRepository
{
    /** Allowed preferences and their valid values. */
    public const ALLOWED = ['theme' => ['system', 'light', 'dark']];

    public function __construct(private PDO $pdo, private string $driver)
    {
    }

    /** @return array<string,string> */
    public function all(): array
    {
        return $this->withTable(function (): array {
            $rows = $this->pdo->query('SELECT name, value FROM aisbp_settings')->fetchAll();
            $out = [];
            foreach ($rows ?: [] as $r) {
                $name = (string)$r['name'];
                $value = (string)$r['value'];
                if (isset(self::ALLOWED[$name]) && in_array($value, self::ALLOWED[$name], true)) {
                    $out[$name] = $value;
                }
            }
            return $out;
        });
    }

    /** Store the valid entries of $prefs (unknown keys and values are ignored). */
    public function save(array $prefs): void
    {
        $this->withTable(function () use ($prefs): void {
            foreach (self::ALLOWED as $name => $values) {
                $value = $prefs[$name] ?? null;
                if (!is_string($value) || !in_array($value, $values, true)) {
                    continue;
                }
                $this->pdo->beginTransaction();
                try {
                    $stmt = $this->pdo->prepare('UPDATE aisbp_settings SET value = ? WHERE name = ?');
                    $stmt->execute([$value, $name]);
                    $exists = $this->pdo->prepare('SELECT COUNT(*) FROM aisbp_settings WHERE name = ?');
                    $exists->execute([$name]);
                    if ((int)$exists->fetchColumn() === 0) {
                        $this->pdo->prepare('INSERT INTO aisbp_settings (name, value) VALUES (?, ?)')->execute([$name, $value]);
                    }
                    $this->pdo->commit();
                } catch (\Throwable $e) {
                    $this->pdo->rollBack();
                    throw $e;
                }
            }
        });
    }

    /** Run $fn; when the settings table is missing, create the schema (idempotent) and retry once. */
    private function withTable(callable $fn): mixed
    {
        try {
            return $fn();
        } catch (\PDOException $e) {
            if ($this->pdo->inTransaction()) {
                $this->pdo->rollBack();
            }
            install_schema($this->pdo, $this->driver);
            return $fn();
        }
    }
}
